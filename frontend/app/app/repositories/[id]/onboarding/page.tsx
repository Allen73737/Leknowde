import { ApiErrorNote, NotIndexedNotice } from "@/components/app/error-note";
import { OnboardingPlan } from "@/components/repo/onboarding-plan";
import { SectionHeading } from "@/components/ui/card";
import { getRepositoryBundle } from "@/lib/app-data";
import { safeGet } from "@/lib/server-api";
import type { OnboardingResponse } from "@/lib/types";

export const metadata = { title: "Onboarding" };

export default async function OnboardingPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const bundle = await getRepositoryBundle(id);

  if (!bundle.data) {
    return <ApiErrorNote error={bundle.error} retryHref={`/app/repositories/${id}/onboarding`} />;
  }
  if (bundle.data.repository.status !== "ready") {
    return <NotIndexedNotice repositoryID={id} status={bundle.data.repository.status} />;
  }

  const result = await safeGet<OnboardingResponse>(`/repositories/${id}/onboarding`);
  if (!result.data) {
    return (
      <ApiErrorNote
        error={result.error}
        retryHref={`/app/repositories/${id}/onboarding`}
        title="Onboarding plan unavailable"
      />
    );
  }

  return (
    <div className="space-y-6">
      <SectionHeading
        title="Onboarding plan"
        description="A path assembled from indexed structure: entry points first, then modules, then the files with the highest connectivity. Nothing here is generated by a language model, and nothing is verified by a test runner."
      />
      <OnboardingPlan repositoryID={id} plan={result.data} />
    </div>
  );
}
