"use client";

import { useRouter } from "next/navigation";
import { useState } from "react";
import {
  AlertTriangle,
  BookOpen,
  Check,
  FilePlus2,
  FileText,
  RefreshCw,
  Trash2,
} from "lucide-react";

import { LogoLoader } from "@/components/brand/logo-loader";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, EmptyState } from "@/components/ui/card";
import { Markdown } from "@/components/ui/markdown";
import { apiDelete, apiPatch, apiPost } from "@/lib/client-api";
import { isApiError } from "@/lib/api-error";
import { cn, formatDateTime, parseMaybeJson, relativeTime } from "@/lib/format";
import { documentKindIcons } from "@/lib/nav";
import type { DocumentRecord, DocumentsResponse, GenerateDocumentResponse } from "@/lib/types";

interface DriftState {
  drifted?: boolean;
  checked?: boolean;
}

export function DocumentationStudio({
  repositoryID,
  initialDocuments,
  kinds,
}: {
  repositoryID: string;
  initialDocuments: DocumentRecord[];
  kinds: DocumentsResponse["kinds"];
}) {
  const router = useRouter();
  const [documents, setDocuments] = useState(initialDocuments);
  const [selectedID, setSelectedID] = useState(initialDocuments[0]?.id ?? "");
  const [kind, setKind] = useState(kinds[0]?.kind ?? "overview");
  const [overwrite, setOverwrite] = useState(false);
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const [conflictKind, setConflictKind] = useState("");

  const selected = documents.find((document) => document.id === selectedID) ?? null;
  const selectedKind = kinds.find((item) => item.kind === kind);

  async function generate(force = false) {
    setBusy("generate");
    setError("");
    setNotice("");
    setConflictKind("");
    try {
      const result = await apiPost<GenerateDocumentResponse>(`/repositories/${repositoryID}/documents`, {
        kind,
        overwrite: force || overwrite,
      });
      setDocuments((current) => {
        const others = current.filter((document) => document.id !== result.document.id && document.kind !== result.document.kind);
        return [result.document, ...others];
      });
      setSelectedID(result.document.id);
      setNotice(
        `${result.document.title} saved. ${result.generated_by_model ? "Prose generated by " + result.provider + "." : "Deterministic fallback used."} ${result.note}`,
      );
      router.refresh();
    } catch (cause) {
      if (isApiError(cause) && cause.status === 409) {
        setConflictKind(kind);
        setError(cause.message);
      } else {
        setError(cause instanceof Error ? cause.message : "Could not generate the document.");
      }
    } finally {
      setBusy("");
    }
  }

  async function setStatus(document: DocumentRecord, status: string) {
    setBusy(`status-${document.id}`);
    setError("");
    try {
      await apiPatch(`/documents/${document.id}`, { status, content: document.content });
      setDocuments((current) =>
        current.map((item) => (item.id === document.id ? { ...item, status } : item)),
      );
      router.refresh();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not update the document.");
    } finally {
      setBusy("");
    }
  }

  async function remove(document: DocumentRecord) {
    if (!window.confirm(`Delete "${document.title}"? This removes the stored document, not source files.`)) return;
    setBusy(`delete-${document.id}`);
    setError("");
    try {
      await apiDelete(`/documents/${document.id}`);
      const remaining = documents.filter((item) => item.id !== document.id);
      setDocuments(remaining);
      if (selectedID === document.id) setSelectedID(remaining[0]?.id ?? "");
      router.refresh();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not delete the document.");
    } finally {
      setBusy("");
    }
  }

  return (
    <div className="space-y-4">
      <Card>
        <div className="p-4">
          <div className="flex items-center gap-2">
            <FilePlus2 className="h-4 w-4 text-faint" aria-hidden="true" />
            <h2 className="text-[0.9375rem] font-semibold text-ink">Generate documentation</h2>
          </div>
          <p className="mt-1 max-w-3xl text-[0.8125rem] leading-relaxed text-muted">
            Documents are assembled from indexed facts. Without a model provider, the deterministic engine produces a
            complete structural draft. With a provider, prose is additive; source facts stay the same.
          </p>
          <div className="mt-3 grid gap-3 lg:grid-cols-[1fr_1.2fr_auto] lg:items-end">
            <label className="block">
              <span className="mb-1.5 block text-xs font-medium text-muted">Document kind</span>
              <select
                value={kind}
                onChange={(event) => {
                  setKind(event.target.value);
                  setConflictKind("");
                }}
                className="h-10 w-full rounded-md border border-line bg-surface px-3 text-sm text-ink focus:border-accent focus:outline-none"
              >
                {kinds.map((item) => (
                  <option key={item.kind} value={item.kind}>
                    {item.title}
                    {item.requires_llm ? " (prose requires a provider)" : ""}
                  </option>
                ))}
              </select>
            </label>
            <p className="text-[0.75rem] leading-relaxed text-faint">
              {selectedKind?.description ?? "Generates a Markdown document from repository facts."}
            </p>
            <Button type="button" loading={busy === "generate"} onClick={() => generate()} disabled={Boolean(busy)}>
              <FilePlus2 className="h-3.5 w-3.5" aria-hidden="true" />
              {documents.some((document) => document.kind === kind) ? "Regenerate" : "Generate"}
            </Button>
          </div>
          <label className="mt-3 flex cursor-pointer items-center gap-2 text-[0.8125rem] text-muted">
            <input
              type="checkbox"
              checked={overwrite}
              onChange={(event) => setOverwrite(event.target.checked)}
              className="h-3.5 w-3.5 accent-[var(--accent)]"
            />
            Overwrite an existing document of this kind without asking
          </label>
          {error ? (
            <div className="mt-3 rounded-md border border-danger/40 bg-danger/5 px-3 py-2">
              <p className="text-[0.8125rem] text-danger">{error}</p>
              {conflictKind ? (
                <Button
                  type="button"
                  size="sm"
                  variant="danger"
                  className="mt-2"
                  loading={busy === "generate"}
                  onClick={() => generate(true)}
                >
                  <RefreshCw className="h-3.5 w-3.5" aria-hidden="true" /> Regenerate and overwrite
                </Button>
              ) : null}
            </div>
          ) : null}
          {notice ? (
            <p className="mt-3 rounded-md border border-success/40 bg-success/5 px-3 py-2 text-[0.8125rem] leading-relaxed text-success">
              {notice}
            </p>
          ) : null}
        </div>
      </Card>

      {documents.length === 0 ? (
        <Card>
          <EmptyState
            icon={<BookOpen className="h-4 w-4" aria-hidden="true" />}
            title="No documents generated yet"
            description="Choose a kind above and generate a draft. Documents are written from indexed structure, so the first one needs no model provider."
          />
        </Card>
      ) : (
      <div className="grid items-start gap-4 lg:grid-cols-[280px_minmax(0,1fr)]">
        <aside className="rounded-card border border-line bg-surface">
          <div className="flex items-center justify-between border-b border-line px-4 py-2.5">
            <p className="text-[0.75rem] font-semibold uppercase tracking-[0.14em] text-faint">Stored documents</p>
            <Badge>{documents.length}</Badge>
          </div>
          {documents.length === 0 ? (
            <div className="px-4 py-8 text-center">
              <FileText className="mx-auto h-4 w-4 text-faint" aria-hidden="true" />
              <p className="mt-2 text-[0.8125rem] text-muted">No documents generated yet.</p>
            </div>
          ) : (
            <ul className="divide-y divide-line">
              {documents.map((document) => {
                const drift = parseMaybeJson<DriftState>(document.drift);
                const Icon = documentKindIcons[document.kind] ?? BookOpen;
                return (
                  <li key={document.id}>
                    <button
                      type="button"
                      onClick={() => setSelectedID(document.id)}
                      className={cn(
                        "flex w-full items-start gap-2.5 px-3 py-2.5 text-left transition-colors",
                        selectedID === document.id ? "bg-raised" : "hover:bg-raised/50",
                      )}
                    >
                      <Icon className={cn("mt-0.5 h-3.5 w-3.5 shrink-0", selectedID === document.id ? "text-accent" : "text-faint")} aria-hidden="true" />
                      <span className="min-w-0">
                        <span className="block truncate text-[0.8125rem] font-medium text-ink">{document.title}</span>
                        <span className="mt-0.5 flex flex-wrap items-center gap-1">
                          <Badge tone={document.status === "published" ? "success" : "neutral"}>{document.status}</Badge>
                          {drift?.drifted ? <Badge tone="warning">drift</Badge> : null}
                        </span>
                        <span className="mt-1 block font-mono text-[0.75rem] text-faint">
                          {relativeTime(document.updated_at)}
                        </span>
                      </span>
                    </button>
                  </li>
                );
              })}
            </ul>
          )}
        </aside>

        <div className="min-w-0 rounded-card border border-line bg-surface">
          {selected ? (
            <>
              <div className="flex flex-col gap-2 border-b border-line px-4 py-3 sm:flex-row sm:items-start sm:justify-between">
                <div className="min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <h2 className="truncate font-display text-sm font-semibold text-ink">{selected.title}</h2>
                    <Badge tone={selected.status === "published" ? "success" : "neutral"}>{selected.status}</Badge>
                    {selected.drift && parseMaybeJson<DriftState>(selected.drift)?.drifted ? (
                      <Badge tone="warning">source drift</Badge>
                    ) : null}
                  </div>
                  <p className="mt-1 font-mono text-[0.75rem] text-faint">
                    {selected.path} · updated {formatDateTime(selected.updated_at)} · fingerprint{" "}
                    {selected.source_fingerprint ? selected.source_fingerprint.slice(0, 12) : "none"}
                  </p>
                  {selected.drift && parseMaybeJson<DriftState>(selected.drift)?.drifted ? (
                    <p className="mt-1.5 flex items-center gap-1.5 text-[0.75rem] text-warning">
                      <AlertTriangle className="h-3 w-3" aria-hidden="true" /> Source structure changed since this
                      document was generated. Regenerate to refresh facts.
                    </p>
                  ) : null}
                </div>
                <div className="flex shrink-0 flex-wrap items-center gap-1.5">
                  {selected.status !== "published" ? (
                    <Button
                      type="button"
                      size="sm"
                      variant="secondary"
                      loading={busy === `status-${selected.id}`}
                      onClick={() => setStatus(selected, "published")}
                    >
                      <Check className="h-3.5 w-3.5" aria-hidden="true" /> Publish
                    </Button>
                  ) : (
                    <Button
                      type="button"
                      size="sm"
                      variant="ghost"
                      loading={busy === `status-${selected.id}`}
                      onClick={() => setStatus(selected, "draft")}
                    >
                      Move to draft
                    </Button>
                  )}
                  <Button
                    type="button"
                    size="sm"
                    variant="danger"
                    loading={busy === `delete-${selected.id}`}
                    onClick={() => remove(selected)}
                  >
                    <Trash2 className="h-3.5 w-3.5" aria-hidden="true" /> Delete
                  </Button>
                </div>
              </div>
              <div className="px-4 py-5">
                {busy === "generate" ? (
                  <p className="flex items-center gap-2 text-[0.8125rem] text-faint">
                    <LogoLoader size={14} decorative /> Generating from repository facts…
                  </p>
                ) : (
                  <Markdown content={selected.content} />
                )}
              </div>
            </>
          ) : (
            <div className="flex min-h-[360px] flex-col items-center justify-center px-6 text-center">
              <BookOpen className="h-5 w-5 text-faint" aria-hidden="true" />
              <p className="mt-2 text-sm font-medium text-ink">Choose a document</p>
              <p className="mt-1 max-w-sm text-[0.8125rem] leading-relaxed text-muted">
                Generate a document from the panel above, then select it here to read, publish or regenerate it.
              </p>
            </div>
          )}
        </div>
      </div>
      )}
    </div>
  );
}
